// Local synthetic data only. Never contact the production backend.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const origin=process.env.DUOFIT_PREVIEW_URL||'http://127.0.0.1:8765';
const output=process.env.DUOFIT_QA_OUTPUT||path.join(__dirname,'../docs/qa/checkin-design');
fs.mkdirSync(output,{recursive:true});
(async()=>{
  const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_BROWSER||'chromium'});
  try{
    const checks=[];
    for(const person of ['hus','wife'])for(const theme of ['light','dark']){
      const context=await browser.newContext({viewport:{width:390,height:844},colorScheme:theme});
      await context.route('**/*',r=>new URL(r.request().url()).origin===origin?r.continue():r.abort());
      const page=await context.newPage(),errors=[],posts=[];
      page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.method()==='POST')posts.push(r.url())});
      await page.goto(origin+`/tests/theme-preview.html?view=diet&person=${person}&theme=${theme}&journal=1`);
      await page.waitForSelector('body[data-preview-ready="true"]');
      assert.equal(await page.locator('.diary-date').count(),7);
      const future=await page.locator('.diary-date[disabled]').count();
      const yesterday=await page.evaluate(()=>{const d=new Date();d.setDate(d.getDate()-1);return [d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-')});
      const today=await page.evaluate(()=>{const d=new Date();return [d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-')});
      // Use a date in the visible week; on Mondays first browse to the previous week.
      const monday=await page.evaluate(()=>new Date().getDay()===1);
      if(monday)await page.locator('[data-diet-week="-1"]').click();
      await page.locator(`[data-diet-date="${yesterday}"]`).click();
      assert.equal(await page.locator('.diary-actions').count(),4,'past own meals can be edited');
      assert.equal(await page.locator(`[data-meal="breakfast"][data-v="over"]`).getAttribute('data-meal-date'),yesterday);
      await page.locator(`[data-meal="breakfast"][data-v="over"]`).click();
      const saved=await page.evaluate(d=>({past:themePreviewApp.getCheckin(d.person,d.yesterday).meals.breakfast,today:themePreviewApp.getCheckin(d.person,d.today).meals.breakfast}),{person,yesterday,today});
      assert.equal(saved.past,'over','past meal updates its own date');assert.equal(saved.today,'plan','past edit leaves today untouched');
      await page.locator('.diary-meal').first().locator('[data-food]').click();
      assert((await page.locator('#foodTitle').innerText()).includes('月'),'past food editor names the date');
      await page.locator('#foodText').fill('鸡蛋 1 个');
      await page.evaluate(()=>themePreviewApp.onFoodText());
      await page.locator('#foodRes input[data-fk="0"]').waitFor();
      await page.locator('[data-food-save]').click();
      const pastFood=await page.evaluate(d=>({past:themePreviewApp.getCheckin(d.person,d.yesterday).food?.breakfast?.kcal,today:themePreviewApp.getCheckin(d.person,d.today).food?.breakfast?.kcal}),{person,yesterday,today});
      assert(pastFood.past>0,'past food saves to selected date');assert.equal(pastFood.today,210,'past food leaves today untouched');
      await page.locator('.diary-meal').first().locator('[data-food]').click();
      assert.equal(await page.locator('#foodText').inputValue(),'鸡蛋 1 个','past meal reopens saved text');
      await page.locator('#foodText').fill('全麦面包 1 片');
      await page.evaluate(()=>themePreviewApp.onFoodText());
      await page.waitForFunction(()=>document.querySelector('#foodRes li')?.textContent.includes('全麦面包'));
      await page.locator('[data-food-save]').click();
      assert((await page.evaluate(d=>themePreviewApp.getCheckin(d.person,d.date).food.breakfast.items[0].n,{person,date:yesterday})).includes('全麦面包'),'past food can be replaced');
      await page.locator('.diary-meal').first().locator('[data-food]').click();
      await page.locator('[data-food-clear]').click();
      const cleared=await page.evaluate(d=>({past:themePreviewApp.getCheckin(d.person,d.yesterday),today:themePreviewApp.getCheckin(d.person,d.today)}),{person,yesterday,today});
      assert.equal(cleared.past.food?.breakfast,undefined,'past food deletion targets selected day');
      assert.equal(cleared.past.meals.breakfast,'plan','deleting food preserves the separate check-in state');
      assert.equal(cleared.today.food.breakfast.kcal,210,'past deletion leaves today untouched');
      assert.equal(await page.locator('.diary-meal').count(),4);
      assert((await page.locator('.diary-day-title').innerText()).includes('昨天'));
      for(let i=0;i<5;i++)await page.locator('[data-diet-week="-1"]').click();
      const blankDate=await page.locator('.diary-date[aria-pressed="true"]').getAttribute('data-diet-date');
      assert.equal(await page.evaluate(d=>themePreviewApp.getCheckin(d.person,d.date).meals?.snack||null,{person,date:blankDate}),null,'empty historical day is selectable');
      assert.equal(await page.locator('.diary-actions').count(),0,'blank day does not show status controls');
      assert.equal(await page.locator('.diary-meal .meal-status.empty').count(),4,'blank meals remain unlogged');
      assert.equal(await page.locator('.diary-edit').filter({hasText:'补打卡'}).count(),4,'each blank meal offers backfill');
      await page.locator('.diary-meal').nth(2).locator('[data-food="snack"]').click();
      assert((await page.locator('#foodLead').innerText()).includes('当前计划'),'historical estimate identifies its comparison range');
      assert(await page.locator('[data-food-save]').isDisabled(),'backfill requires recognized food and calories');
      await page.addStyleTag({content:'#toast{visibility:hidden !important}'});
      await page.locator('#foodDlg').screenshot({path:path.join(output,`backfill-dialog-${person}-${theme}-390.png`)});
      await page.setViewportSize({width:320,height:844});
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'320px backfill dialog fits');
      await page.locator('#foodDlg').screenshot({path:path.join(output,`backfill-dialog-${person}-${theme}-320.png`)});
      await page.setViewportSize({width:390,height:844});
      await page.locator('#foodText').fill('苹果 1 个');await page.evaluate(()=>themePreviewApp.onFoodText());
      await page.locator('#foodRes input[data-fk="0"]').waitFor();
      assert.equal(await page.locator('[data-food-save]').innerText(),'确认补打卡');
      await page.locator('[data-food-save]').click();
      const backfilled=await page.evaluate(d=>themePreviewApp.getCheckin(d.person,d.date),{person,date:blankDate});
      assert(['plan','over'].includes(backfilled.meals.snack)&&backfilled.food.snack.kcal>0,'confirmation classifies and saves selected historical meal');
      assert.equal(await page.locator('.diary-actions').count(),1,'confirmed meal now has normal status controls');
      await page.locator('.diet-week').screenshot({path:path.join(output,`backfill-confirmed-${person}-${theme}-390.png`)});
      await page.locator('[data-diet-today]').click();
      assert.equal(await page.locator('.diary-date[aria-pressed="true"]').getAttribute('data-diet-date'),today);
      assert.equal(await page.locator('[data-meal="snack"]').count(),0,'today diet log also keeps an unlogged meal unset');
      await page.locator('[data-food="snack"]').click();assert(await page.locator('#foodDlg').isVisible());
      await page.locator('#foodText').fill('苹果 1 个');await page.evaluate(()=>themePreviewApp.onFoodText());
      await page.locator('#foodRes input[data-fk="0"]').waitFor();await page.locator('[data-food-save]').click();
      assert.equal(await page.locator('[data-meal="snack"]').count(),3,'today meal gets normal choices after confirmation');
      await page.getByRole('button',{name:'记录',exact:true}).click();
      const numbers=await page.locator('.habit-number b').allTextContents();assert.deepEqual(numbers,person==='hus'?['5','3']:['3','5']);
      assert.equal(await page.locator('.habit-day').count(),28);
      await page.locator('#mForm input[name="weight"]').fill('77.2');
      await page.locator(`[data-history-date="${yesterday}"]`).click();
      assert.equal(await page.locator('#mForm input[name="weight"]').inputValue(),'77.2','history navigation keeps unsaved health input');
      assert((await page.locator('.history-day .diary-day-title').innerText()).includes('昨天'));
      await page.locator('[data-history-window="-1"]').click();
      assert.equal(await page.locator('#mForm input[name="weight"]').inputValue(),'77.2');
      await page.locator('[data-history-window="1"]').click();
      for(const view of ['record','diet'])for(const width of [320,390]){
        await page.setViewportSize({width,height:844});
        await page.getByRole('button',{name:view==='diet'?'饮食':'记录',exact:true}).click();
        assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal page overflow');
        const section=page.locator(view==='diet'?'.diet-week':'.checkin-history');await section.scrollIntoViewIfNeeded();
        await page.screenshot({path:path.join(output,`${view}-${person}-${theme}-${width}.png`)});
      }
      assert.deepEqual(errors,[]);assert.deepEqual(posts,[]);
      checks.push({person,theme,futureDaysDisabled:future,pastMealEdited:true,blankHadNoStatus:true,backfillGeneratedStatus:true,dialogRequiresFood:true,todayMealWorks:true,historyInputPreserved:true,smallScreenFits:true,errors});
      await context.close();
    }
    fs.writeFileSync(path.join(output,'browser-results.json'),JSON.stringify(checks,null,2)+'\n');
    console.log('PASS daily/week history, meal actions, couple streaks, health input preservation, light/dark themes and 320/390px layouts');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
